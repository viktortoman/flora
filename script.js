function switchMode(mode, updateUrl = false) {
  const d = data[mode];
  if (!d) return;

  document.querySelectorAll('.mode-btn').forEach(btn => {
    btn.classList.remove('active');
    btn.classList.add('text-slate');
    btn.classList.remove('text-white');
  });

  const activeBtnId = mode === 'sales' ? 'btn-sales' : 'btn-pm';
  const activeBtn = document.getElementById(activeBtnId);

  if(activeBtn) {
    activeBtn.classList.add('active');
    activeBtn.classList.remove('text-slate');
    activeBtn.classList.add('text-white');
  }

  if (updateUrl) {
    const newUrl = window.location.protocol + "//" + window.location.host + window.location.pathname + '?mode=' + mode;
    window.history.replaceState({path: newUrl}, '', newUrl);
  }

  updateText('hero-prefix', d.heroPrefix);
  updateText('hero-role-1', d.role1);
  updateText('hero-role-2', d.role2);
  updateText('hero-desc', d.desc);
  updateText('hero-badge-text', d.heroBadge);

  const iconContainer = document.getElementById('hero-icons-container');
  if (iconContainer && d.heroIcons) {
    iconContainer.innerHTML = d.heroIcons.map(item =>
      `<div class="flex flex-col items-center group fade-in">
                <i class="${item.icon} text-3xl mb-1 group-hover:text-gold transition"></i>
                <span class="text-xs font-semibold">${item.label}</span>
            </div>`
    ).join('');
  }

  updateText('step-1-title', d.steps[0].title);
  updateList('step-1-list', d.steps[0].list);
  updateText('step-2-title', d.steps[1].title);
  updateList('step-2-list', d.steps[1].list);
  updateText('step-3-title', d.steps[2].title);
  updateList('step-3-list', d.steps[2].list);
  updateText('step-5-title', d.steps[3].title);
  updateList('step-5-list', d.steps[3].list);

  updateText('nitro-title', d.nitro.title);
  updateText('nitro-badge', d.nitro.badge);
  updateText('nitro-desc', d.nitro.desc);

  updateList('nitro-results', d.nitro.results);
  updateList('nitro-tasks', d.nitro.tasks);

  updateText('max-role', d.maxBusiness.role);
  updateText('max-desc', d.maxBusiness.desc);
  updateList('max-tasks', d.maxBusiness.tasks);

  updateText('footer-role', d.footerRole);

  const skillContainer = document.getElementById('soft-skills-list');
  if(skillContainer) {
    skillContainer.innerHTML = d.skills.map(skill =>
      `<li class="flex items-start gap-3 fade-in">
                <i class="fa-solid fa-check text-gold mt-1"></i>
                <span class="text-sm text-slate">${skill}</span>
            </li>`
    ).join('');
  }

  const hardSkillsContainer = document.getElementById('hard-skills-grid');
  if(hardSkillsContainer && d.hardSkills) {
    hardSkillsContainer.innerHTML = d.hardSkills.map(skill =>
      `<div class="fade-in">
                <h4 class="font-bold text-navy text-sm mb-2">${skill.title}</h4>
                <p class="text-xs text-slate leading-relaxed">${skill.text}</p>
            </div>`
    ).join('');
  }
}

function updateText(id, text) {
  const el = document.getElementById(id);
  if(el) {
    el.innerHTML = text;
    el.classList.remove('fade-in');
    void el.offsetWidth;
    el.classList.add('fade-in');
  }
}

function updateList(elementId, items) {
  const el = document.getElementById(elementId);
  if(el) {
    el.innerHTML = items.map(item => `<li class="fade-in">${item}</li>`).join('');
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const btnSales = document.getElementById('btn-sales');
  const btnPm = document.getElementById('btn-pm');

  if (btnSales) {
    btnSales.addEventListener('click', () => switchMode('sales', true));
  }
  if (btnPm) {
    btnPm.addEventListener('click', () => switchMode('pm', true));
  }

  const urlParams = new URLSearchParams(window.location.search);
  const modeParam = urlParams.get('mode');

  if (modeParam === 'sales') {
    switchMode('sales', false);
  } else {
    switchMode('pm', false);
  }

  const menuBtn = document.getElementById('mobile-menu-btn');
  const closeBtn = document.getElementById('close-menu-btn');
  const mobileMenu = document.getElementById('mobile-menu');
  const mobileLinks = document.querySelectorAll('.mobile-link');

  function openMenu() {
    mobileMenu.classList.add('visible-menu');
    document.body.style.overflow = 'hidden';
  }

  function closeMenu() {
    mobileMenu.classList.remove('visible-menu');
    document.body.style.overflow = '';
  }

  if (menuBtn) {
    menuBtn.addEventListener('click', openMenu);
  }

  if (closeBtn) {
    closeBtn.addEventListener('click', closeMenu);
  }

  mobileLinks.forEach(link => {
    link.addEventListener('click', closeMenu);
  });

  document.getElementsByClassName('current-year')[0].innerHTML = new Date().getFullYear().toString();
});